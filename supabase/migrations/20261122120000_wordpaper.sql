CREATE SCHEMA IF NOT EXISTS wordpaper;
REVOKE ALL ON SCHEMA wordpaper FROM PUBLIC;

CREATE TABLE IF NOT EXISTS wordpaper.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  username_key TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user'
);

CREATE TABLE IF NOT EXISTS wordpaper.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  csrf_token TEXT NOT NULL,
  allow_legacy_import INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  authenticated_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS sessions_user_id ON wordpaper.sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expires_at ON wordpaper.sessions(expires_at);

CREATE TABLE IF NOT EXISTS wordpaper.password_credentials (
  user_id BIGINT PRIMARY KEY REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  password_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wordpaper.user_state (
  user_id BIGINT NOT NULL REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  namespace TEXT NOT NULL,
  value_json TEXT NOT NULL CHECK (value_json::json IS NOT NULL),
  revision BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, namespace)
);

CREATE TABLE IF NOT EXISTS wordpaper.user_speech (
  user_id BIGINT PRIMARY KEY REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  base_url TEXT NOT NULL,
  model TEXT NOT NULL,
  voice TEXT NOT NULL,
  key_cipher TEXT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wordpaper.user_models (
  user_id BIGINT PRIMARY KEY REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  base_url TEXT NOT NULL,
  protocol TEXT NOT NULL,
  model TEXT NOT NULL,
  key_cipher TEXT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wordpaper.auth_identities (
  provider TEXT NOT NULL,
  provider_subject TEXT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  email TEXT,
  email_verified INTEGER NOT NULL DEFAULT 0,
  display_name TEXT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (provider, provider_subject)
);
CREATE UNIQUE INDEX IF NOT EXISTS auth_identity_per_user ON wordpaper.auth_identities(user_id, provider);

CREATE TABLE IF NOT EXISTS wordpaper.email_verifications (
  email_key TEXT PRIMARY KEY,
  code_hash TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS email_verifications_expires_at ON wordpaper.email_verifications(expires_at);

CREATE TABLE IF NOT EXISTS wordpaper.oauth_flows (
  state_hash TEXT PRIMARY KEY,
  binding_hash TEXT NOT NULL,
  provider TEXT NOT NULL,
  code_verifier TEXT,
  initiating_session_hash TEXT,
  redirect_uri TEXT NOT NULL,
  next_path TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  purpose TEXT NOT NULL DEFAULT 'login',
  expected_subject TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS oauth_flows_expires_at ON wordpaper.oauth_flows(expires_at);

CREATE TABLE IF NOT EXISTS wordpaper.device_flows (
  device_hash TEXT PRIMARY KEY,
  user_code TEXT NOT NULL UNIQUE,
  challenge TEXT NOT NULL,
  user_id BIGINT REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wordpaper.app_meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS wordpaper.user_word_examples (
  user_id BIGINT NOT NULL REFERENCES wordpaper.users(id) ON DELETE CASCADE,
  library TEXT NOT NULL,
  entry_key TEXT NOT NULL,
  example_json TEXT NOT NULL CHECK (example_json::json IS NOT NULL),
  model TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, library, entry_key)
);

REVOKE ALL ON ALL TABLES IN SCHEMA wordpaper FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA wordpaper FROM PUBLIC;
DO $$
DECLARE
  client_role NAME;
BEGIN
  FOR client_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role') LOOP
    EXECUTE format('REVOKE ALL ON SCHEMA wordpaper FROM %I', client_role);
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA wordpaper FROM %I', client_role);
    EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA wordpaper FROM %I', client_role);
  END LOOP;
END
$$;
